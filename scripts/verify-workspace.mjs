// Conversation workspace acceptance with public fixture data and local responses.
import { _electron as electron } from 'playwright-core';
import { createRequire } from 'node:module';
import { mkdtempSync, mkdirSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { resolve } from 'node:path';
import assert from 'node:assert/strict';
import { startMockGateway } from './mock-gateway.mjs';
const packaged = process.argv.includes('--packaged');
const require = createRequire(import.meta.url);
const directory = mkdtempSync('/tmp/stomylos-workspace-');
const output = `test-results/workspace-${packaged ? 'packaged' : 'native'}`;
mkdirSync(output, { recursive: true });
const seed = spawnSync(require('electron'), ['scripts/seed-ui.mjs', directory], { env: { ...process.env, ELECTRON_RUN_AS_NODE: '1' }, encoding: 'utf8' });
assert.equal(seed.status, 0, seed.stderr);
const mock = await startMockGateway({ delay: 0 });
const env = { ...process.env, STOMYLOS_DATA_DIR: directory, STOMYLOS_TEST_ENDPOINT: mock.endpoint, ...(packaged ? { STOMYLOS_PACKAGED_TEST: '1' } : {}) };
for (const key of ['ELECTRON_RUN_AS_NODE', 'ELECTRON_RENDERER_URL', 'STOMYLOS_LIVE_VERIFY']) delete env[key];
let app;
const errors = [], checks = [];
try {
  app = await electron.launch({ executablePath: packaged ? resolve(process.env.STOMYLOS_VERIFY_BUNDLE ?? 'release/linux-unpacked/stomylos') : require('electron'), args: packaged ? [] : ['.'], env, chromiumSandbox: true });
  const page = await app.firstWindow(); page.setDefaultTimeout(15000); page.on('pageerror', e => errors.push(e.message));
  const button = name => page.getByRole('button', { name, exact: true });
  const shot = name => page.screenshot({ path: `${output}/${name}.png`, scale: 'css' });
  await button('Partner: Automatic').waitFor();
  assert.equal(await page.locator('aside').isVisible(), false);
  assert.equal((await page.locator('header').innerText()).includes('Stomylos'), false);
  assert.equal((await page.locator('body').innerText()).includes('Maya'), false);
  assert.equal(await page.locator('.starter-dock .bubble').count(), 1);
  assert.equal(await page.locator('.transcript .bubble').count(), 0);
  await shot('01-starter');
  await button('Start with your own topic').click();
  const input = page.locator('textarea[aria-label="Your message"]');
  await input.fill('An exact unsent draft.\n한국어');
  await shot('02-direct');
  await button('Show history').click();
  await page.locator('.history-item').nth(1).click();
  await button('Return to current chat').waitFor();
  const before = await page.locator('.transcript').innerText();
  await page.locator('main').evaluate(node => { node.scrollTop = 20; node.dispatchEvent(new Event('scroll')); });
  const scroll = await page.locator('main').evaluate(n => n.scrollTop);
  await button('Learning').click();
  assert.equal(await page.locator('.transcript').innerText(), before);
  assert.equal(await page.locator('main').evaluate(n => n.scrollTop), scroll);
  assert.equal(await page.locator('main').isVisible(), true);
  await shot('03-reports-beside-chat');
  await button('Back to conversation').click();
  await button('Return to current chat').click();
  assert.equal(await input.inputValue(), 'An exact unsent draft.\n한국어');
  await button('Hide history').click();
  checks.push('Default closed library; no header wordmark or invented name; starter dock; report browsing preserves transcript/scroll; history return preserves exact draft');
  await button('Help!').click();
  await button('Use in draft').waitFor();
  assert.equal(await page.locator('.composer > .genie-dock').count(), 1);
  assert.equal(await page.locator('.modal-overlay').count(), 0);
  assert.equal(await input.getAttribute('readonly'), '');
  await shot('04-genie');
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setContentSize(760, 620));
  await page.waitForTimeout(100);
  const regions = await page.evaluate(() => ['header','main','.genie-dock','.genie-composer','.composer > textarea'].map(selector => {
    const r = document.querySelector(selector).getBoundingClientRect(); return { selector, x:r.x, y:r.y, width:r.width, height:r.height, viewport:innerHeight };
  }));
  for (const r of regions) assert.ok(r.x >= 0 && r.y >= 0 && r.y+r.height <= r.viewport+1, JSON.stringify(r));
  assert.ok(regions.find(r => r.selector === 'main').height >= 100);
  const helpBounds = await page.locator('.genie-history').boundingBox(), applyBounds = await button('Use in draft').boundingBox();
  assert.ok(applyBounds.y >= helpBounds.y && applyBounds.y + applyBounds.height <= helpBounds.y + helpBounds.height + 1, 'Latest apply action stays visible after resize');
  await shot('05-genie-minimum');
  await button('Close Genie').click();
  await button('End chat').click();
  const review = page.getByRole('button', { name:/^Analysis details/ });
  await review.waitFor(); assert.equal(await review.getAttribute('aria-expanded'), 'false');
  await review.click(); assert.equal(await review.getAttribute('aria-expanded'), 'true');
  await shot('06-feedback');
  await button('Show history').click();
  await button('Learning').click();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await shot('07-library-minimum');
  checks.push('Attached focus-isolated Genie without overlay; main draft visible; minimum-size transcript/follow-up/apply fit; optional feedback; report library fits minimum width');
  assert.deepEqual(errors, []);
  writeFileSync(`${output}/report.json`, JSON.stringify({ packaged, directory, checks, regions, errors, paidRequests:0 }, null, 2));
  console.log(JSON.stringify({ output, checks, errors }));
} finally { await app?.close(); await new Promise(r => mock.server.close(r)); }
