// Public mocked sessions exercise renewal alongside grammar and interactive replies.
import { _electron as electron } from 'playwright-core';
import { createRequire } from 'node:module';
import { mkdtempSync, mkdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { tmpdir } from 'node:os';
import assert from 'node:assert/strict';
import { startMockGateway } from './mock-gateway.mjs';
const executablePath = createRequire(import.meta.url)('electron');
const directory = mkdtempSync(join(tmpdir(), 'stomylos-starter-ui-'));
const local = await startMockGateway({ delay: 35, backgroundDelay: 7000 });
const env = { ...process.env, STOMYLOS_DATA_DIR: directory, STOMYLOS_TEST_ENDPOINT: local.endpoint };
delete env.ELECTRON_RUN_AS_NODE; delete env.STOMYLOS_LIVE_VERIFY;
const report = { status: 'running', directory, checks: [], errors: [] };
let app;
try {
  app = await electron.launch({ executablePath, args: ['.'], env, chromiumSandbox: true });
  const page = await app.firstWindow(); page.on('pageerror', error => report.errors.push(error.message));
  const input = page.getByRole('textbox', { name: 'Your message' }); await input.waitFor();
  const original = await page.evaluate(async () => (await window.stomylos.command('snapshot')).unfinished.id);
  await input.fill('A draft survives a question change. 한글');
  await page.getByRole('button', { name: /Another question/ }).click();
  assert.equal(await input.inputValue(), 'A draft survives a question change. 한글'); assert.equal(local.requests.length, 0);
  await input.fill('I took a quiet walk and noticed the river was very clear.'); await input.press('Enter');
  await page.getByText('Writing…', { exact: true }).waitFor();
  await page.getByText('Writing…', { exact: true }).waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: 'End chat', exact: true }).click();
  await page.getByRole('button', { name: 'More options' }).click();
  await page.getByRole('menuitem', { name: 'Conversation details', exact: true }).click();
  await page.getByRole('button', { name: /Starter renewal.*Generating questions/ }).waitFor();
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Start another chat' }).click(); await input.waitFor();
  const second = await page.evaluate(async () => (await window.stomylos.command('snapshot')).unfinished.id);
  const before = await page.evaluate(id => window.stomylos.command('loadSession', { sessionId: id }), second);
  const old = await page.evaluate(id => window.stomylos.command('loadSession', { sessionId: id }), original);
  assert.equal(old.renewal.state, 'running'); assert.equal(old.session.analysis_state, 'running');
  await input.fill('I would like to describe the bakery near my home.'); await input.press('Enter');
  await page.getByText('Writing…', { exact: true }).waitFor();
  const during = await page.evaluate(id => window.stomylos.command('loadSession', { sessionId: id }), original);
  assert.equal(during.renewal.state, 'running'); assert.equal(during.session.analysis_state, 'running');
  assert.equal(await input.evaluate(node => node === document.activeElement), true);
  report.checks.push('Another question preserves draft without requests; next chat streams with grammar and renewal both running');
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByRole('dialog').waitFor(); await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('alert').count(), 0);
  await page.getByText('Writing…', { exact: true }).waitFor({ state: 'hidden' });
  const deadline = Date.now() + 20000;
  let finished;
  do {
    finished = await page.evaluate(id => window.stomylos.command('loadSession', { sessionId: id }), original);
    if (finished.renewal.state === 'completed' && finished.session.analysis_state === 'completed') break;
    if (Date.now() > deadline) throw new Error('Background completion timed out');
    await page.waitForTimeout(100);
  } while (true);
  const after = await page.evaluate(id => window.stomylos.command('loadSession', { sessionId: id }), second);
  assert.equal(after.session.starter_text, before.session.starter_text); assert.equal(after.messages[0].content, before.messages[0].content);
  if (!await page.locator('aside').isVisible()) await page.getByRole('button', { name: 'Show history', exact: true }).click();
  await page.locator('.history-item').filter({ hasText: old.session.starter_text }).click();
  await page.getByRole('button', { name: 'More options' }).click();
  await page.getByRole('menuitem', { name: 'Conversation details', exact: true }).click();
  const disclosure = page.getByRole('button', { name: /Starter renewal.*2 new questions saved/ });
  await disclosure.click(); await page.getByText('New questions replenish the local pool as space becomes available.').waitFor();
  assert.equal(await page.getByRole('button', { name: 'Try starter renewal again' }).count(), 0);
  await page.getByRole('button', { name: /Request details/ }).click();
  await page.getByText('Starter generation', { exact: true }).waitFor();
  await disclosure.scrollIntoViewIfNeeded(); await page.waitForTimeout(250);
  mkdirSync('test-results', { recursive: true }); await page.screenshot({ path: resolve('test-results/starter-renewal.png') });
  report.checks.push('Background promotion preserves current session question; completed disclosure and safe generator details render');
  const child = app.process(); const stopped = new Promise(resolve => child.once('exit', resolve));
  await page.evaluate(() => window.stomylos.command('close')); await stopped; app = null;
  const count = local.requests.length;
  app = await electron.launch({ executablePath, args: ['.'], env, chromiumSandbox: true });
  const reopened = await app.firstWindow(); await reopened.getByRole('textbox', { name: 'Your message' }).waitFor();
  assert.deepEqual(await reopened.evaluate(id => window.stomylos.command('loadSession', { sessionId: id }), original), finished);
  assert.equal(local.requests.length, count); assert.equal(count, 6);
  report.checks.push('Reopen preserves generated result and active chat with no automatic requests');
  assert.deepEqual(report.errors, []); report.status = 'passed'; report.requests = count;
  console.log(JSON.stringify(report, null, 2));
} finally {
  mkdirSync('test-results', { recursive: true }); writeFileSync('test-results/starter-native-report.json', JSON.stringify(report, null, 2));
  await app?.close().catch(() => undefined); await new Promise(resolve => local.server.close(resolve));
}
